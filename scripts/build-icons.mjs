// Extracts just the icons the page uses from the Iconify sets the Figma design
// was built with, so we don't ship whole icon packs. Re-run after adding an icon:
//   npm run icons
import { createRequire } from "node:module";
import { writeFileSync, mkdirSync } from "node:fs";
import { getIconData, iconToSVG, iconToHTML, replaceIDs } from "@iconify/utils";
const require = createRequire(import.meta.url);

const inline = {
  world: "subway:world",
  store: "carbon:store",
  packageCheck: "lucide:package-check",
  usersRound: "lucide:users-round",
  link: "mingcute:link-line",
  package: "uil:package",
  usersLine: "clarity:users-line",
  checkFill: "lets-icons:check-fill",
  headset: "stash:headset",
  flagUk: "twemoji:flag-united-kingdom",
  flagQatarSmall: "emojione-v1:flag-for-qatar",
  mail: "hugeicons:mail-01",
  call: "hugeicons:call",
  location: "hugeicons:location-06",
  arrowDown: "hugeicons:arrow-down-01",
  instagram: "hugeicons:instagram",
  twitter: "hugeicons:new-twitter",
  facebook: "hugeicons:facebook-01",
  apple: "mdi:apple",
  googlePlay: "mdi:google-play",
  lock: "lucide:lock-keyhole",
};

const load = (set) => require(`@iconify-json/${set}/icons.json`);
const out = {};
for (const [key, full] of Object.entries(inline)) {
  const [set, name] = full.split(":");
  const data = getIconData(load(set), name);
  if (!data) throw new Error(`missing icon ${full}`);
  const svg = iconToSVG(data);
  out[key] = { viewBox: svg.attributes.viewBox, body: replaceIDs(svg.body, key) };
}
writeFileSync(
  "src/lib/icons.ts",
  `// Generated by scripts/build-icons.mjs — do not edit by hand.\nexport const icons = ${JSON.stringify(out, null, 2)} as const;\nexport type IconName = keyof typeof icons;\n`,
);

// Round country flags (same style as the design's flag circles) written as files.
const flags = { usa: "us", uae: "ae", singapore: "sg", korea: "kr", uk: "gb", jordan: "jo", turkey: "tr", china: "cn", kuwait: "kw", australia: "au", qatar: "qa" };
mkdirSync("public/figma/flags", { recursive: true });
for (const [file, code] of Object.entries(flags)) {
  const data = getIconData(load("circle-flags"), code);
  const svg = iconToSVG(data, { height: 96 });
  writeFileSync(`public/figma/flags/${file}.svg`, iconToHTML(replaceIDs(svg.body, file), svg.attributes));
}
console.log(`icons: ${Object.keys(out).length} inline, ${Object.keys(flags).length} flag files`);
